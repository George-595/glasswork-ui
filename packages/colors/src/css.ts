import { EFFECTS, type Effect, ROLES, type Role, THEMES, type Theme } from './roles.ts';

/* Writes the role table out as CSS: one block of custom properties per skin × mode, in the
   cascade order that makes the right block win, then the glass skin's solid fallbacks, and a
   Tailwind v4 theme that maps every role to a colour utility (bg-canvas, text-fg,
   border-border-input, bg-primary-hover…). Generated files carry a header saying so; the
   check fails if they drift from this source (`npm run build --workspace @apps/colors`). */

const HEADER = `/* GENERATED by @apps/colors (src/css.ts) from src/palette.ts + src/roles.ts.
   Do not edit: change the source and run \`npm run build --workspace @apps/colors\`. */\n`;

function block(selector: string, theme: Theme, indent = ''): string {
  const lines = [
    ...ROLES.map((r: Role) => `${indent}  --${r}: ${theme.roles[r]};`),
    ...EFFECTS.map((e: Effect) => `${indent}  --${e}: ${theme.effects[e]};`),
  ];
  return `${indent}${selector} {\n${lines.join('\n')}\n${indent}}\n`;
}

/* Cascade order (later wins at equal specificity):
     :root                                      enterprise dark, the default      (0,1,0)
     :root[data-theme="light"]                  enterprise light                  (0,2,0)
     @media light: :root:not([data-theme=dark]) enterprise light, system pref     (0,2,0)
     :root[data-skin="glass"]                   glass dark                        (0,2,0)
     :root[data-skin="glass"][data-theme=light] glass light                       (0,3,0)
     @media light: …glass…:not([data-theme=dark]) glass light, system pref        (0,3,0)
   The glass fallbacks come last at (0,3,0) so they beat glass light too. */
export function colorsCss(): string {
  const light = '@media (prefers-color-scheme: light)';
  return [
    HEADER,
    block(':root', THEMES['enterprise-dark']),
    block(':root[data-theme="light"]', THEMES['enterprise-light']),
    `${light} {\n${block(':root:not([data-theme="dark"])', THEMES['enterprise-light'], '  ')}}\n`,
    block(':root[data-skin="glass"]', THEMES['glass-dark']),
    block(':root[data-skin="glass"][data-theme="light"]', THEMES['glass-light']),
    `${light} {\n${block(':root[data-skin="glass"]:not([data-theme="dark"])', THEMES['glass-light'], '  ')}}\n`,
    `/* Glass, solid: no transparency wanted (or forced colours), or no backdrop-filter at all.
   Translucent surfaces become the opaque solid surface. :is([data-theme], :not([data-theme]))
   matches every root and lifts the selector to (0,3,0), so it beats glass light as well. */
@media (prefers-reduced-transparency: reduce), (forced-colors: active) {
  :root[data-skin="glass"]:is([data-theme], :not([data-theme])) {
    --surface: var(--surface-solid);
    --raised: var(--surface-solid);
    --overlay: var(--surface-solid);
    --bar: var(--surface-solid);
    --sunken: var(--canvas);
    --app-backdrop: none;
  }
}
@supports not ((backdrop-filter: blur(1px)) or (-webkit-backdrop-filter: blur(1px))) {
  :root[data-skin="glass"]:is([data-theme], :not([data-theme])) {
    --surface: var(--surface-solid);
    --raised: var(--surface-solid);
    --overlay: var(--surface-solid);
    --bar: var(--surface-solid);
  }
}
`,
    `:root {\n  color-scheme: dark;\n}\n:root[data-theme="light"] {\n  color-scheme: light;\n}\n${light} {\n  :root:not([data-theme="dark"]) {\n    color-scheme: light;\n  }\n}\n`,
  ].join('\n');
}

/* The Tailwind theme: Tailwind's own palette is wiped (--color-*: initial), so the only
   colour utilities that exist are the roles. `inline` keeps each utility pointing at the live
   custom property, so skin and mode switch everything at runtime. */
export function themeCss(): string {
  return `${HEADER}@theme inline {\n  --color-*: initial;\n  --color-transparent: transparent;\n  --color-current: currentColor;\n${ROLES.map((r) => `  --color-${r}: var(--${r});`).join('\n')}\n}\n`;
}
